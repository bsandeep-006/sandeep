// Function Declaration
function greet() {
    console.log("Hello from a function declaration!");
}

// Function Expression
const sayGoodbye = function () {
    console.log("Goodbye from a function expression!");
};

// Arrow Function
const sayThanks = () => {
    console.log("Thanks from an arrow function!");
};

// Function Calls
greet();         // Calls the function declaration
sayGoodbye();    // Calls the function expression
sayThanks();     // Calls the arrow function
